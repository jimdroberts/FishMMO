using System.Collections.Generic;
using FishMMO.Shared.Biomes;
using UnityEditor;
using UnityEngine;

namespace FishMMO.Shared.WorldDesign
{
	/// <summary>One piece of cave glow art, as the dressing places it: its prefab and how it sits on the rock.</summary>
	public struct CaveGlowArt
	{
		/// <summary>The generated prefab; null until the art is generated (<see cref="CaveArt.TryGlow"/> answers false then).</summary>
		public GameObject Prefab;
		/// <summary>Its name under the generated prefabs (<c>Cave/Cave_Crystal_Violet_2</c>).</summary>
		public string Name;
		public CaveGlowKind Kind;
		/// <summary>The hue's (or ore's) name: IceBlue, Teal, Copper, Starmetal…</summary>
		public string Hue;
		/// <summary>How it is set against the rock: which way is out of the surface, where its origin is (<see cref="CaveMount"/>).</summary>
		public CaveMount Mount;
		/// <summary>
		/// How far it stands out of its surface at scale 1, metres: a floor piece's top over its origin, a wall piece's reach
		/// out along −z, a roof piece's drop below its origin.
		/// </summary>
		public float Height;
		/// <summary>Half its widest extent along its surface at scale 1, metres (x/z on a floor or roof, x/y on a wall).</summary>
		public float Radius;
		/// <summary>How far it reaches behind its origin into the rock at scale 1, metres: how uneven the rock may be under it without a gap showing.</summary>
		public float Root;
		/// <summary>The colour of the light it gives, for an emitter beside it (black for an ore that only shines).</summary>
		public Color Light;
		/// <summary>The reach a light placed with it should have, metres; 0 where none is wanted (glow-worms, plain ore).</summary>
		public float SuggestedReach;
		/// <summary>The hue bits (8–9 of the seed) of a <see cref="SceneEmitterKind.Crystal"/> emitter for its light (<see cref="CaveArt.EmitterSeed"/>); −1 for none.</summary>
		public int EmitterHue;
		/// <summary>Whether its light flickers (a cave crystal whose kind does, <see cref="CaveMineral.Flickers"/>): a cold glow's, not a crystal light's.</summary>
		public bool Flickers;
		/// <summary>Whether its prefab carries a collider (crystals, giant fungi).</summary>
		public bool Collides;
	}

	/// <summary>
	/// The cave and mine kit as the cave dressing places it (2026-10-13): the glow art by kind, hue and variant, and the
	/// structure pieces' names, modules and pivots. Editor-only, like the rest of the generator; it decides no generated byte.
	/// </summary>
	/// <remarks>
	/// <para>
	/// <b>Glow art</b> (<see cref="TryGlow"/>; generated with the structure kit by "Generate biome art"). Every piece glows
	/// by its emissive material on its own; only the brightest few want a light, and the placer adds that as a
	/// <see cref="SceneEmitterKind.Crystal"/> emitter with <see cref="CaveGlowArt.SuggestedReach"/> and
	/// <see cref="EmitterSeed"/> (SiteLightPool's sixteen pooled lights take the nearest). Mounts:
	/// <list type="bullet">
	/// <item><b>Floor</b> (Crystal, GiantCrystal, Fungus, GiantFungus, TowerFungus, MidFungus, Puffballs): origin at the foot, up +y; rotate +y to the surface's
	/// normal to set a crystal on a wall or a roof, as geodes grow.</item>
	/// <item><b>Wall</b> (ShelfFungus, OreVein, GlowOreVein, ShelfTiers, GlowVine): origin on the wall's surface, +z into the rock, the piece
	/// standing out along −z, up +y; a seam runs along x.</item>
	/// <item><b>Roof</b> (GlowWorms, GlowRoots, HangingRoots, GlowSilk, TapRoots): origin on the roof, hanging down −y (a tap root is stretched in y to the floor).</item>
	/// </list>
	/// Hues: crystals IceBlue, Green, Violet, Amber; fungi (every fungus, glowroot and glow-vine kind) Teal, Blue, Gold; glow-worms Blue; ore Copper, Iron, Silver,
	/// Gold; glowing ore Starmetal, Emberstone; hanging tree roots and tap roots Earth, Pale; glow-worm silk the fungi's; guano heaps (a floor piece) Fresh, Dry. A hue or variant index past the end wraps round.
	/// </para>
	/// <para>
	/// <b>Structure pieces</b> (<see cref="Piece"/>, StructurePieces.Cave.cs). Ladders: <see cref="Ladder"/> and
	/// <see cref="RopeLadder"/> are 3 m modules, <see cref="LadderShort"/> and <see cref="RopeLadderShort"/> 1 m, origin at the
	/// foot's middle, rungs across x a third of a metre apart (the first a sixth up, so any mix stacks evenly), the back at
	/// z = 0 against the wall, the climber's side −z; stack them with <see cref="LadderStack"/>. <see cref="ClimbRope"/>: a
	/// 3 m module hung from its top at the origin, knots every half metre; <see cref="ClimbRopeStack"/>. Its anchors
	/// (<see cref="RopeAnchor"/> at a lip, <see cref="RopeBeam"/> across a shaft) hold the rope at their origin. Spans
	/// (<see cref="RopeBridgeSpan"/>, <see cref="TrestleSpan"/>) are 4 m along z with the deck's top at the origin, laid end
	/// to end; <see cref="RopeBridgeEnd"/> stands at a walk's end (posts at z = 0, the walk leaving toward +z: turn it 180°
	/// for the far end); <see cref="TrestleBent"/> stands under each trestle joint, scaled in y by
	/// <see cref="TrestleBentScale"/>. Lamps: <see cref="HangingLantern"/> from its fixing (origin, hangs −y),
	/// <see cref="WallLantern"/> from its back plate (z = 0 on the wall, out along −z), <see cref="LanternStand"/> on the
	/// ground; each gives off a Lamp emitter by itself when laid through PointOfInterestSiteContext.AddProp.
	/// </para>
	/// </remarks>
	public static class CaveArt
	{
		// ── Structure pieces ──────────────────────────────────────────

		public const string Ladder = "Ladder", LadderShort = "LadderShort", RopeLadder = "RopeLadder", RopeLadderShort = "RopeLadderShort";
		public const string ClimbRope = "ClimbRope", RopeAnchor = "RopeAnchor", RopeBeam = "RopeBeam";
		public const string RopeBridgeSpan = "RopeBridgeSpan", RopeBridgeEnd = "RopeBridgeEnd", TrestleSpan = "TrestleSpan", TrestleBent = "TrestleBent";
		public const string HangingLantern = "HangingLantern", WallLantern = "WallLantern", LanternStand = "LanternStand";
		public const string ShaftCollar = "ShaftCollar", MiningTools = "MiningTools", OreSacks = "OreSacks", WaterBucket = "WaterBucket", MineSign = "MineSign";
		public const string CookingFire = "CookingFire", StrawBed = "StrawBed";

		/// <summary>A ladder module's height and a short one's, metres.</summary>
		public const float LadderModule = StructurePieces.LadderModule, LadderShortModule = StructurePieces.LadderShortModule;
		/// <summary>Rung to rung, metres.</summary>
		public const float LadderRungPitch = StructurePieces.LadderRungPitch;
		/// <summary>How far a ladder stands off its wall (z from 0 to −this), metres.</summary>
		public const float LadderDepth = StructurePieces.LadderDepth;
		/// <summary>A climbing rope module's length below its top, metres.</summary>
		public const float ClimbRopeModule = StructurePieces.ClimbRopeModule;
		/// <summary>A rope walk's or a trestle's span along z, metres.</summary>
		public const float SpanModule = StructurePieces.CaveSpanModule;
		/// <summary>The clear opening a shaft collar frames, metres square.</summary>
		public const float ShaftOpening = StructurePieces.ShaftOpening;
		/// <summary>How far a wall lantern stands out from its wall, metres.</summary>
		public const float WallLanternReach = StructurePieces.WallLanternReach;

		/// <summary>A hanging lantern's bottom below its fixing, metres (v0 1.38, v1 1.02).</summary>
		public static float HangingLanternDrop(int variant) => StructurePieces.HangingLanternDrops[Mathf.Clamp(variant, 0, StructurePieces.HangingLanternDrops.Length - 1)];

		/// <summary>A structure piece's generated prefab (null until the art is generated); throws for an unknown id.</summary>
		public static GameObject Piece(string id, int variant, StructureFinish finish = StructureFinish.None) => StructureKit.Prefab(id, variant, finish);

		/// <summary>
		/// The ladder modules that climb <paramref name="height"/> metres from a foot at y = 0, bottom first: as many 3 m
		/// modules as fit, then 1 m ones for what is left (rounded up, so the top rung is never short of the lip). Each is a
		/// piece id and the height of its foot.
		/// </summary>
		public static List<(string id, float foot)> LadderStack(float height, bool rope)
		{
			var stack = new List<(string, float)>();
			float y = 0f;
			string tall = rope ? RopeLadder : Ladder, small = rope ? RopeLadderShort : LadderShort;
			while (height - y >= LadderModule - 0.01f)
			{
				stack.Add((tall, y));
				y += LadderModule;
			}
			while (height - y > 0.05f)
			{
				stack.Add((small, y));
				y += LadderShortModule;
			}
			return stack;
		}

		/// <summary>
		/// The climbing rope modules that hang <paramref name="length"/> metres from a top at y = 0: each module's top (0,
		/// −3, −6 …) and its y scale (1, the last one shorter, never under a third).
		/// </summary>
		public static List<(float top, float scaleY)> ClimbRopeStack(float length)
		{
			var stack = new List<(float, float)>();
			float y = 0f;
			while (length + y > 0.05f)
			{
				float left = length + y;
				stack.Add((y, Mathf.Clamp(left / ClimbRopeModule, 1f / 3f, 1f)));
				y -= ClimbRopeModule;
			}
			return stack;
		}

		/// <summary>The y scale that sets a trestle bent's sill on a floor <paramref name="depth"/> metres below the deck.</summary>
		public static float TrestleBentScale(float depth, int variant)
		{
			float own = StructurePieces.TrestleBentDepths[Mathf.Clamp(variant, 0, StructurePieces.TrestleBentDepths.Length - 1)];
			return Mathf.Max(0.1f, depth) / own;
		}

		// ── Glow art ──────────────────────────────────────────────────

		/// <summary>How many hues (or ores) a kind comes in.</summary>
		public static int HueCount(CaveGlowKind kind) => ProceduralArtCatalogue.CaveGlow(kind).Hues.Length;

		/// <summary>A hue's name (an index past the end wraps round).</summary>
		public static string HueName(CaveGlowKind kind, int hue)
		{
			CaveGlowHue[] hues = ProceduralArtCatalogue.CaveGlow(kind).Hues;
			return hues[Wrap(hue, hues.Length)].Name;
		}

		/// <summary>A hue's index by name (ordinal, case-insensitive), or −1.</summary>
		public static int HueIndex(CaveGlowKind kind, string name)
		{
			CaveGlowHue[] hues = ProceduralArtCatalogue.CaveGlow(kind).Hues;
			for (int i = 0; i < hues.Length; i++)
			{
				if (string.Equals(hues[i].Name, name, System.StringComparison.OrdinalIgnoreCase))
				{
					return i;
				}
			}
			return -1;
		}

		/// <summary>How many shapes a kind has.</summary>
		public static int VariantCount(CaveGlowKind kind) => ProceduralArtCatalogue.CaveGlow(kind).Variants;

		/// <summary>
		/// A piece of glow art: its prefab and how it sits (hue and variant wrap round). False, with everything but the prefab
		/// filled in, when the art has not been generated yet (run Generate Biome Art).
		/// </summary>
		public static bool TryGlow(CaveGlowKind kind, int hue, int variant, out CaveGlowArt art)
		{
			CaveGlowFamily family = ProceduralArtCatalogue.CaveGlow(kind);
			CaveGlowHue h = family.Hues[Wrap(hue, family.Hues.Length)];
			int v = Wrap(variant, family.Variants);
			string name = ProceduralArtCatalogue.CaveGlowPrefab(kind, h.Name, v);
			Measure(family, v, out float height, out float radius, out float root);
			art = new CaveGlowArt
			{
				Prefab = AssetDatabase.LoadAssetAtPath<GameObject>(ProceduralArtCatalogue.PrefabPath(name)),
				Name = name,
				Kind = kind,
				Hue = h.Name,
				Mount = family.Mount,
				Height = height,
				Radius = radius,
				Root = root,
				Light = h.Light,
				SuggestedReach = h.EmitterHue >= 0 ? family.Reach : 0f,
				EmitterHue = h.EmitterHue,
				Collides = family.Collides,
			};
			return art.Prefab != null;
		}

		/// <summary>
		/// An emitter seed carrying a light's hue in bits 8–9 (<see cref="SceneEmitterKind.Crystal"/>: 0 violet, 1 blue,
		/// 2 green, 3 amber); the seed unchanged for a hue of −1.
		/// </summary>
		public static uint EmitterSeed(uint seed, int emitterHue) => emitterHue < 0 ? seed : (seed & ~0x300u) | ((uint)(emitterHue & 3) << 8);

		// ── Cave crystals (2026-10-16, I6c) ───────────────────────────

		/// <summary>
		/// The generated prefab name of a cave crystal's variant (the variant wraps round): the rock art's formation for selenite
		/// and frost crystal (<c>Rocks/Formations/…Gypsum_Crystal_2</c>), else its own (<c>Cave/Cave_Mineral_Amethyst_2</c>).
		/// </summary>
		public static string MineralPrefabName(BiomeCaveCrystalKind kind, int variant)
		{
			CaveMineral mineral = ProceduralArtCatalogue.CaveMineralOf(kind);
			if (mineral.Formation)
			{
				return RockArtNames.FormationPrefab(mineral.FormationRock, mineral.FormationShape, Wrap(variant, RockTypes.VariantCount));
			}
			return ProceduralArtCatalogue.CaveMineralPrefab(mineral.Kind, Wrap(variant, ProceduralArtCatalogue.CaveMineralVariants));
		}

		/// <summary>A cave crystal's prefab (null until the art is generated: a formation's by the rock art, the rest by the structures').</summary>
		public static GameObject MineralPrefab(BiomeCaveCrystalKind kind, int variant)
			=> AssetDatabase.LoadAssetAtPath<GameObject>(ProceduralArtCatalogue.PrefabPath(MineralPrefabName(kind, variant)));

		/// <summary>
		/// A cave crystal built in its own habit as a piece of floor glow art (its light, reach and hue its kind's), for what lines
		/// a cave's ways where the biome grows a glowing kind. False for a formation's crystal (selenite, frost crystal: not glow
		/// art) and, with everything but the prefab filled in, while the art is not generated.
		/// </summary>
		public static bool TryMineral(BiomeCaveCrystalKind kind, int variant, out CaveGlowArt art)
		{
			CaveMineral mineral = ProceduralArtCatalogue.CaveMineralOf(kind);
			art = default;
			if (mineral.Formation)
			{
				return false;
			}
			int v = Wrap(variant, ProceduralArtCatalogue.CaveMineralVariants);
			MeasureMineral(mineral.Habit, v, out float height, out float radius, out float root);
			string name = ProceduralArtCatalogue.CaveMineralPrefab(kind, v);
			art = new CaveGlowArt
			{
				Prefab = AssetDatabase.LoadAssetAtPath<GameObject>(ProceduralArtCatalogue.PrefabPath(name)),
				Name = name,
				Kind = CaveGlowKind.Crystal,
				Hue = mineral.Hue.Name,
				Mount = CaveMount.Floor,
				Height = height,
				Radius = radius,
				Root = root,
				Light = mineral.Hue.Light,
				SuggestedReach = mineral.Hue.EmitterHue >= 0 ? ProceduralArtCatalogue.CaveMineralReach : 0f,
				EmitterHue = mineral.Hue.EmitterHue,
				Flickers = mineral.Flickers,
				Collides = true,
			};
			return art.Prefab != null;
		}

		private static readonly Dictionary<(CaveMineralHabit, int), (float height, float radius, float root)> mineralsMeasured = new Dictionary<(CaveMineralHabit, int), (float, float, float)>();

		/// <summary>A cave crystal habit's variant's extents on its floor mount, from its finest level at the art's seed (built once).</summary>
		private static void MeasureMineral(CaveMineralHabit habit, int variant, out float height, out float radius, out float root)
		{
			lock (mineralsMeasured)
			{
				if (!mineralsMeasured.TryGetValue((habit, variant), out (float height, float radius, float root) m))
				{
					Bounds b = CaveGlowMeshes.BuildMineral(habit, variant, 0, ProceduralArtCatalogue.DefaultSeed).Bounds;
					m = (b.max.y, Mathf.Max(Mathf.Max(b.max.x, -b.min.x), Mathf.Max(b.max.z, -b.min.z)), Mathf.Max(0f, -b.min.y));
					mineralsMeasured[(habit, variant)] = m;
				}
				height = m.height;
				radius = m.radius;
				root = m.root;
			}
		}

		private static int Wrap(int i, int n) => n <= 0 ? 0 : ((i % n) + n) % n;

		private static readonly Dictionary<(CaveGlowKind, int), (float height, float radius, float root)> measured = new Dictionary<(CaveGlowKind, int), (float, float, float)>();

		/// <summary>A variant's extents along and across its mount, from its finest level at the art's seed (built once, milliseconds).</summary>
		private static void Measure(CaveGlowFamily family, int variant, out float height, out float radius, out float root)
		{
			lock (measured)
			{
				if (!measured.TryGetValue((family.Shape, variant), out (float height, float radius, float root) m))
				{
					Bounds b = CaveGlowMeshes.Build(family.Shape, variant, 0, ProceduralArtCatalogue.DefaultSeed).Bounds;
					switch (family.Mount)
					{
						case CaveMount.Wall:
							m = (-b.min.z, Mathf.Max(Mathf.Max(b.max.x, -b.min.x), Mathf.Max(b.max.y, -b.min.y)), Mathf.Max(0f, b.max.z));
							break;
						case CaveMount.Roof:
							m = (-b.min.y, Mathf.Max(Mathf.Max(b.max.x, -b.min.x), Mathf.Max(b.max.z, -b.min.z)), Mathf.Max(0f, b.max.y));
							break;
						default:
							m = (b.max.y, Mathf.Max(Mathf.Max(b.max.x, -b.min.x), Mathf.Max(b.max.z, -b.min.z)), Mathf.Max(0f, -b.min.y));
							break;
					}
					measured[(family.Shape, variant)] = m;
				}
				height = m.height;
				radius = m.radius;
				root = m.root;
			}
		}
	}
}
#endif
