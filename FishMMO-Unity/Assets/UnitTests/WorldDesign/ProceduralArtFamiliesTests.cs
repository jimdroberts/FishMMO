using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using FishMMO.Shared.WorldDesign;
using NUnit.Framework;

namespace FishMMO.UnitTests.WorldDesign
{
	/// <summary>
	/// The generation split by family (<see cref="ProceduralArtFamilies"/>): a change to one family's code rebuilds that
	/// family and what is made from it, a change to a shared source rebuilds everything, and no generator source goes
	/// unhashed.
	/// </summary>
	public class ProceduralArtFamiliesTests
	{
		private const string Folder = "Assets/Scripts/Shared/Implementation/Tools/Extensions/Unity/Editor/World/ProceduralArt";

		/// <summary>Sources in the generator's folder that decide no generated byte (tools, renders, the bookkeeping).</summary>
		private static readonly string[] NotGenerating =
		{
			"BiomeArtAuthoring.cs", "ProceduralArtAutoGenerate.cs", "ProceduralArtBuildGroup.cs", "ProceduralArtLedger.cs",
			"ProceduralArtMigration.cs", "ProceduralArtPayload.cs", "ProceduralArtTextureImport.cs", "ProceduralArtVariants.cs",
			"ProceduralArtWrapperCheck.cs", "ProceduralArtFamilies.cs", "RockComparisonRender.cs", "StructureKitRender.cs",
			"VegetationVariationRender.cs", "WorldEditorPhotoImport.cs", "VineBiomes.cs", "StructureInteriors.cs", "CaveArt.cs",
		};

		/// <summary>The sources every family is made with: a change to one rebuilds everything.</summary>
		private static readonly string[] Shared =
		{
			"BiomeArtGenerator.cs", "BiomeArtGenerator.Parallel.cs", "BiomeArtSpec.cs", "MeshBuilder.cs", "ProceduralArtCatalogue.cs", "ProceduralArtFileIds.cs",
			"ProceduralNoise.cs", "SurfaceCatalogue.cs", "SurfaceSynth.cs",
		};

		[Test]
		public void EveryGeneratorSourceIsHashedOrDecidesNoBytes()
		{
			Assert.That(Directory.Exists(Folder), Is.True, "run from the project root");
			foreach (string path in Directory.GetFiles(Folder, "*.cs"))
			{
				string file = Path.GetFileName(path);
				if (NotGenerating.Contains(file))
				{
					continue;
				}
				Assert.That(ProceduralArtPayload.SourceFiles, Does.Contain(file),
					$"{file} is in the generator's folder but not hashed: an edit to it would never mark the art stale. Add it to SourceFiles (or to NotGenerating here if it decides no generated byte).");
			}
		}

		[Test]
		public void OnlyTheCoreIsShared()
		{
			var shared = ProceduralArtPayload.SourceFiles.Where(f => ProceduralArtFamilies.FamiliesOfFile(f).Length == 0).OrderBy(f => f).ToArray();
			Assert.That(shared, Is.EquivalentTo(Shared),
				"a hashed source in no family rebuilds EVERY family when it changes; give it a family rule unless every family really is made with it");
		}

		[Test]
		public void NewStructurePiecesAreTheStructuresFromTheirFirstLine()
		{
			Assert.That(ProceduralArtFamilies.FamiliesOfFile("StructurePieces.Anything.cs"), Is.EqualTo(new[] { ArtFamily.Structures }));
		}

		private static Dictionary<ArtFamily, string> Prints(Dictionary<string, string> texts)
			=> ProceduralArtFamilies.Fingerprints("format=1;seed=7", texts.Keys, f => texts.TryGetValue(f, out string t) ? t : null);

		private static Dictionary<string, string> Sources()
		{
			var texts = new Dictionary<string, string>();
			foreach (string file in ProceduralArtPayload.SourceFiles)
			{
				texts[file] = "// " + file;
			}
			return texts;
		}

		private static HashSet<ArtFamily> Changed(Dictionary<ArtFamily, string> before, Dictionary<ArtFamily, string> after)
		{
			var recorded = before.ToDictionary(kv => kv.Key.ToString(), kv => kv.Value);
			return ProceduralArtFamilies.Dirty(after, recorded);
		}

		[Test]
		public void AStructureEditRebuildsOnlyTheStructures()
		{
			Dictionary<string, string> texts = Sources();
			Dictionary<ArtFamily, string> before = Prints(texts);
			texts["StructurePieces.Town.cs"] += " edited";
			Assert.That(Changed(before, Prints(texts)), Is.EquivalentTo(new[] { ArtFamily.Structures }));
		}

		[Test]
		public void ATreeEditRebuildsTheTreesAndTheClimbersOnThem()
		{
			Dictionary<string, string> texts = Sources();
			Dictionary<ArtFamily, string> before = Prints(texts);
			texts["TreeMeshes.cs"] += " edited";
			Assert.That(Changed(before, Prints(texts)), Is.EquivalentTo(new[] { ArtFamily.Trees, ArtFamily.Vines }));
		}

		[Test]
		public void ARockEditRebuildsTheRocksAndWhatIsMadeFromThem()
		{
			Dictionary<string, string> texts = Sources();
			Dictionary<ArtFamily, string> before = Prints(texts);
			texts["RockMeshes.cs"] += " edited";
			Assert.That(Changed(before, Prints(texts)), Is.EquivalentTo(new[] { ArtFamily.Rocks, ArtFamily.Cliffs, ArtFamily.Deadwood }));
		}

		[Test]
		public void ASharedEditRebuildsEverything()
		{
			Dictionary<string, string> texts = Sources();
			Dictionary<ArtFamily, string> before = Prints(texts);
			texts["MeshBuilder.cs"] += " edited";
			Assert.That(Changed(before, Prints(texts)), Is.EquivalentTo(ProceduralArtFamilies.All));
			// So does a different seed or format.
			var reseeded = ProceduralArtFamilies.Fingerprints("format=1;seed=8", Sources().Keys, f => Sources()[f]);
			Assert.That(Changed(before, reseeded), Is.EquivalentTo(ProceduralArtFamilies.All));
		}

		[Test]
		public void NothingChangedRebuildsNothing_AndNoRecordRebuildsEverything()
		{
			Dictionary<ArtFamily, string> prints = Prints(Sources());
			Assert.That(Changed(prints, Prints(Sources())), Is.Empty, "fingerprints are deterministic");
			Assert.That(ProceduralArtFamilies.Dirty(prints, null), Is.EquivalentTo(ProceduralArtFamilies.All));
			Assert.That(ProceduralArtFamilies.Dirty(prints, new Dictionary<string, string>()), Is.EquivalentTo(ProceduralArtFamilies.All));
		}

		[Test]
		public void BuildingOnEveryCoreGivesTheSameMeshesInTheSameOrder()
		{
			var items = new List<(BushSpecies species, int lod)>();
			foreach (BushSpecies species in ProceduralArtCatalogue.Bushes.Take(4))
			{
				for (int lod = 0; lod < BushMeshes.Levels; lod++)
				{
					items.Add((species, lod));
				}
			}
			const int seed = 1234;
			MeshBuilder[] parallel = BiomeArtGenerator.BuildAll(items, d => BushMeshes.Build(in d.species, d.lod, seed));
			for (int i = 0; i < items.Count; i++)
			{
				BushSpecies species = items[i].species;
				MeshBuilder serial = BushMeshes.Build(in species, items[i].lod, seed);
				Assert.That(parallel[i].Positions, Is.EqualTo(serial.Positions), $"{items[i].species.Name} level {items[i].lod}: positions");
				Assert.That(parallel[i].Submeshes.Count, Is.EqualTo(serial.Submeshes.Count));
				for (int s = 0; s < serial.Submeshes.Count; s++)
				{
					Assert.That(parallel[i].Submeshes[s], Is.EqualTo(serial.Submeshes[s]), $"{items[i].species.Name} level {items[i].lod}: triangles");
				}
			}
		}

		[Test]
		public void AFailedBuildIsThrownOnTheCallingThread()
		{
			var items = Enumerable.Range(0, 32).ToList();
			var ex = Assert.Throws<InvalidOperationException>(() => BiomeArtGenerator.BuildAll(items, i => i == 17 ? throw new InvalidOperationException("seventeen") : i));
			Assert.That(ex.Message, Is.EqualTo("seventeen"));
			Assert.That(BiomeArtGenerator.BuildAll(items, i => i * 2), Is.EqualTo(items.Select(i => i * 2).ToArray()), "results in the items' order");
		}

		[Test]
		public void StepsRunWhenTheirFamilyIsDirty_AndUnknownStepsAreShared()
		{
			var structures = new HashSet<ArtFamily> { ArtFamily.Structures };
			Assert.That(ProceduralArtFamilies.StepDirty("Structure: Tavern", structures), Is.True);
			Assert.That(ProceduralArtFamilies.StepDirty("Cliff sections", structures), Is.False);
			Assert.That(ProceduralArtFamilies.StepDirty("Tree: Oak", structures), Is.False);
			// Shared and unknown steps run whenever anything rebuilds, never when nothing does.
			Assert.That(ProceduralArtFamilies.StepDirty("Materials", structures), Is.True);
			Assert.That(ProceduralArtFamilies.StepDirty("A step nobody named yet", structures), Is.True);
			Assert.That(ProceduralArtFamilies.StepDirty("Materials", new HashSet<ArtFamily>()), Is.False);
			// Everything (null) runs every step.
			Assert.That(ProceduralArtFamilies.StepDirty("Cliff sections", null), Is.True);
			// The atlas step writes the vines' atlas too.
			Assert.That(ProceduralArtFamilies.StepDirty("Foliage atlas", new HashSet<ArtFamily> { ArtFamily.Vines }), Is.True);
		}
	}
}
