#!/usr/bin/env bash
#
# Publishes the standalone Updater for every platform FishMMO ships a client on.
#
# The .NET apphost is platform- and architecture-specific, so a Windows client and a
# Linux client each need their own binary; there is no portable one. All targets
# cross-publish from any host, so a single machine (including an Arch/CachyOS box) can
# produce the whole set.
#
# Output, one directory per RID:
#   ../Builds/Updater/Release/net8.0/<rid>/publish/Updater[.exe]
#
# That layout is exactly what the FishMMO Dashboard's BuildExecutor.CopyUpdaterToBuild
# looks for when it copies the updater into a client build, so publishing here is what
# makes a client build shippable.
#
# Usage:
#   ./publish-updater.sh                  # win-x64 and linux-x64 (the shipped defaults)
#   ./publish-updater.sh --all            # every RID declared in Updater.csproj
#   ./publish-updater.sh linux-arm64 ...  # an explicit list
#
set -euo pipefail

script_dir="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
project="${script_dir}/Updater/Updater.csproj"
repo_root="$(cd -- "${script_dir}/.." && pwd)"
assets_file="${script_dir}/Updater/obj/project.assets.json"
updater_notices="${repo_root}/Licenses/THIRD-PARTY-NOTICES-Updater.txt"

# Copies the notices the Updater must ship with into a publish folder. The names carry an
# 'Updater-' prefix because the client build copies this whole folder next to the client,
# which has its own LICENSE.txt and THIRD-PARTY-NOTICES.txt.
#   Updater-THIRD-PARTY-NOTICES.txt          generated by Licenses/generate_notices.py
#   Updater-dotnet-LICENSE.txt               from the .NET runtime pack this publish used
#   Updater-dotnet-THIRD-PARTY-NOTICES.txt   from the same runtime pack
copy_notices() {
	local rid="$1" dir="$2"
	if [[ ! -f "${updater_notices}" ]]; then
		echo "error: '${updater_notices}' is missing; run 'python3 Licenses/generate_notices.py'." >&2
		return 1
	fi
	cp -f "${updater_notices}" "${dir}/Updater-THIRD-PARTY-NOTICES.txt"

	# The runtime pack a self-contained publish bundles is the one the restore resolved,
	# recorded in project.assets.json together with the NuGet packages folder.
	local packages_path version pack_dir
	packages_path="$(sed -n 's/.*"packagesPath": *"\([^"]*\)".*/\1/p' "${assets_file}" | head -n 1)"
	version="$(grep -A 1 "\"name\": *\"Microsoft.NETCore.App.Runtime.${rid}\"" "${assets_file}" \
		| sed -n 's/.*"version": *"\[\([^,]*\),.*/\1/p' | head -n 1)"
	pack_dir="${packages_path%/}/microsoft.netcore.app.runtime.${rid}/${version}"
	if [[ -z "${packages_path}" || -z "${version}" || ! -f "${pack_dir}/LICENSE.TXT" || ! -f "${pack_dir}/THIRD-PARTY-NOTICES.TXT" ]]; then
		echo "error: the .NET runtime pack for '${rid}' was not found (looked in '${pack_dir}')." >&2
		return 1
	fi
	cp -f "${pack_dir}/LICENSE.TXT" "${dir}/Updater-dotnet-LICENSE.txt"
	cp -f "${pack_dir}/THIRD-PARTY-NOTICES.TXT" "${dir}/Updater-dotnet-THIRD-PARTY-NOTICES.txt"
	chmod 644 "${dir}/Updater-THIRD-PARTY-NOTICES.txt" "${dir}/Updater-dotnet-LICENSE.txt" "${dir}/Updater-dotnet-THIRD-PARTY-NOTICES.txt"
	echo "    notices: Updater-THIRD-PARTY-NOTICES.txt, .NET runtime ${version} licence and notices"
}

# Defaults: the two targets Unity can actually produce a standalone client for.
default_rids=(win-x64 linux-x64)
# Everything Updater.csproj declares, for shipping to hosts Unity does not target directly.
all_rids=(win-x64 win-x86 win-arm64 linux-x64 linux-arm64 osx-x64 osx-arm64)

if [[ $# -eq 0 ]]; then
	rids=("${default_rids[@]}")
elif [[ "$1" == "--all" ]]; then
	rids=("${all_rids[@]}")
else
	rids=("$@")
fi

if ! command -v dotnet >/dev/null 2>&1; then
	echo "error: 'dotnet' is not on PATH. Install the .NET 8 SDK (or newer) first." >&2
	exit 1
fi

echo "Publishing Updater for: ${rids[*]}"
echo

for rid in "${rids[@]}"; do
	echo "=== ${rid} ==="
	# Self-contained + single-file + compression come from Updater.csproj, which applies
	# them whenever a RuntimeIdentifier is set. Passing them here too would just be a
	# second place to keep in sync.
	dotnet publish "${project}" -c Release -r "${rid}" --nologo

	publish_dir="${script_dir}/../Builds/Updater/Release/net8.0/${rid}/publish"
	case "${rid}" in
		win-*) exe="Updater.exe" ;;
		*)     exe="Updater" ;;
	esac

	if [[ ! -f "${publish_dir}/${exe}" ]]; then
		echo "error: expected '${publish_dir}/${exe}' but it was not produced." >&2
		exit 1
	fi

	# The executable bit does not survive a copy onto a filesystem that drops it, and the
	# Dashboard re-applies it after copying; set it here so the publish output is directly
	# runnable too.
	[[ "${exe}" == "Updater" ]] && chmod +x "${publish_dir}/${exe}"

	copy_notices "${rid}" "${publish_dir}"

	echo "    -> ${publish_dir}/${exe}"
	echo
done

echo "Done. The FishMMO Dashboard copies these into client builds automatically."
